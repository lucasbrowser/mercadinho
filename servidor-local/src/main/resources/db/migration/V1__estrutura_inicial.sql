CREATE TABLE usuario (
    id UUID PRIMARY KEY,
    nome_usuario VARCHAR(80) NOT NULL UNIQUE,
    hash_senha VARCHAR(255) NOT NULL,
    nome_exibicao VARCHAR(160) NOT NULL,
    perfil VARCHAR(30) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE produto (
    id UUID PRIMARY KEY,
    codigo_barras VARCHAR(64) NOT NULL UNIQUE,
    nome VARCHAR(180) NOT NULL,
    preco_venda NUMERIC(12,2) NOT NULL CHECK (preco_venda >= 0),
    preco_custo NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (preco_custo >= 0),
    quantidade_estoque NUMERIC(12,3) NOT NULL DEFAULT 0,
    estoque_minimo NUMERIC(12,3) NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE venda (
    id UUID PRIMARY KEY,
    numero_comprovante BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    situacao VARCHAR(24) NOT NULL,
    subtotal NUMERIC(12,2) NOT NULL,
    valor_desconto NUMERIC(12,2) NOT NULL DEFAULT 0,
    valor_total NUMERIC(12,2) NOT NULL,
    operador_id UUID REFERENCES usuario(id),
    criada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE item_venda (
    id UUID PRIMARY KEY,
    venda_id UUID NOT NULL REFERENCES venda(id),
    produto_id UUID NOT NULL REFERENCES produto(id),
    codigo_barras_registrado VARCHAR(64) NOT NULL,
    nome_produto_registrado VARCHAR(180) NOT NULL,
    quantidade NUMERIC(12,3) NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(12,2) NOT NULL CHECK (preco_unitario >= 0),
    valor_total NUMERIC(12,2) NOT NULL CHECK (valor_total >= 0)
);

CREATE TABLE fila_sincronizacao (
    id UUID PRIMARY KEY,
    tipo_entidade VARCHAR(80) NOT NULL,
    entidade_id UUID NOT NULL,
    tipo_evento VARCHAR(120) NOT NULL,
    dados JSONB NOT NULL,
    criada_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sincronizada_em TIMESTAMPTZ,
    tentativas INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX indice_produto_nome ON produto (nome);
CREATE INDEX indice_venda_data ON venda (criada_em);
CREATE INDEX indice_fila_pendente ON fila_sincronizacao (criada_em) WHERE sincronizada_em IS NULL;
